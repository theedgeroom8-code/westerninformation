/**
 * Regenerates lib/teamLogos.ts from ESPN's public team directory.
 *   node scripts/gen-team-logos.js
 *
 * The games board matches The Odds API team names to ESPN's, then hotlinks the
 * small (72px) ESPN logo. Teams that don't match fall back to a monogram badge,
 * so a missing logo never breaks a card. Run this when a new college team
 * starts appearing on the board without a logo.
 *
 * NOTE: ESPN's CDN is not a licensed logo source — see BOARD-GUIDE.md.
 */
const fs = require("fs");
const path = require("path");

const norm = (s) =>
  s.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase()
    .replace(/[’'`.]/g, "").replace(/&/g, "and").replace(/[^a-z0-9]+/g, " ").trim();

// Odds API name → ESPN name, for the few schools the two feeds spell differently.
const ALIASES = {
  "Sam Houston State Bearkats": "Sam Houston Bearkats",
  "Southern Mississippi Golden Eagles": "Southern Miss Golden Eagles",
  "Appalachian State Mountaineers": "App State Mountaineers",
  "Houston Baptist Huskies": "Houston Christian Huskies",
  "UMass Minutemen": "Massachusetts Minutemen",
  "LIU Sharks": "Long Island University Sharks",
};

async function teams(url) {
  const r = await fetch(url);
  if (!r.ok) throw new Error(`${url} → HTTP ${r.status}`);
  const j = await r.json();
  return j.sports[0].leagues[0].teams.map((t) => t.team);
}

(async () => {
  const nfl = await teams("https://site.api.espn.com/apis/site/v2/sports/football/nfl/teams?limit=100");
  const cfb = await teams("https://site.api.espn.com/apis/site/v2/sports/football/college-football/teams?limit=1000");

  // NFL: [logo slug, board label] — the label follows the sportsbook style "BUF Bills"
  const nflMap = {};
  for (const t of nfl) nflMap[norm(t.displayName)] = [t.abbreviation.toLowerCase(), `${t.abbreviation} ${t.shortDisplayName}`];

  // College: [ESPN id, short school name] — "Colorado St", "Miami OH", "UMass"
  const cfbMap = {};
  for (const t of cfb) cfbMap[norm(t.displayName)] = [Number(t.id), t.shortDisplayName || t.displayName];
  const aliasMap = {};
  for (const [from, to] of Object.entries(ALIASES)) {
    if (cfbMap[norm(to)] === undefined) throw new Error(`alias target missing: ${to}`);
    aliasMap[norm(from)] = cfbMap[norm(to)];
  }

  const body = (m) => Object.entries(m).sort(([a], [b]) => a.localeCompare(b))
    .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n");

  const out = `// GENERATED by scripts/gen-team-logos.js from ESPN's team directory — do not edit by hand.
// Keys are normalised team names (lower-case, accents/punctuation stripped).

const NFL: Record<string, [string, string]> = {
${body(nflMap)}
};

const COLLEGE: Record<string, [number, string]> = {
${body({ ...cfbMap, ...aliasMap })}
};

export const normTeam = (s: string): string =>
  s.normalize("NFD").replace(/[\\u0300-\\u036f]/g, "").toLowerCase()
    .replace(/[’'\`.]/g, "").replace(/&/g, "and").replace(/[^a-z0-9]+/g, " ").trim();

/** Small (72px) logo URL for a team, or null when we don't know the team. */
export function teamLogoUrl(sport: string, teamName: string): string | null {
  const key = normTeam(teamName);
  if (sport === "NFL") {
    const hit = NFL[key];
    return hit ? \`https://a.espncdn.com/combiner/i?img=/i/teamlogos/nfl/500/\${hit[0]}.png&w=72&h=72\` : null;
  }
  const hit = COLLEGE[key];
  return hit ? \`https://a.espncdn.com/combiner/i?img=/i/teamlogos/ncaa/500/\${hit[0]}.png&w=72&h=72\` : null;
}

/** Compact card label — "BUF Bills", "Colorado St" — falling back to the full name. */
export function teamShortName(sport: string, teamName: string): string {
  const hit = sport === "NFL" ? NFL[normTeam(teamName)] : COLLEGE[normTeam(teamName)];
  return hit ? hit[1] : teamName;
}

/** Fallback badge: initials on a colour derived from the name. */
export function teamMonogram(teamName: string): { text: string; color: string } {
  const words = teamName.replace(/[^A-Za-z0-9 ]/g, "").trim().split(/\\s+/).filter(Boolean);
  const text = (words.length > 1 ? words.slice(0, 2).map((w) => w[0]).join("") + (words.length > 3 ? words[2][0] : "") : (words[0] || "?").slice(0, 2)).toUpperCase();
  let h = 0;
  for (let i = 0; i < teamName.length; i++) h = (h * 31 + teamName.charCodeAt(i)) % 360;
  return { text, color: \`hsl(\${h}, 45%, 38%)\` };
}
`;
  const file = path.join(__dirname, "..", "lib", "teamLogos.ts");
  fs.writeFileSync(file, out);
  console.log(`wrote ${path.relative(process.cwd(), file)} — ${Object.keys(nflMap).length} NFL, ${Object.keys(cfbMap).length} college, ${Object.keys(aliasMap).length} aliases`);
})().catch((e) => { console.error(e.message); process.exit(1); });
